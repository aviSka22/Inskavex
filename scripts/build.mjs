// Builds the static site from src/ into dist/. No dependencies required.
//
//   node scripts/build.mjs
//
// Steps: copy public files → fingerprint fonts, CSS and JS → render pages →
// generate sitemap.xml, robots.txt and Cloudflare Pages _headers.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { launchIssues, loadConfig } from './lib/config.mjs';
import { escapeHtml, readFrontMatter, render } from './lib/template.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
// BUILD_OUT_DIR lets the test suite build configuration variants side by side.
const DIST = path.resolve(ROOT, process.env.BUILD_OUT_DIR || 'dist');

const hash = (content) => crypto.createHash('sha256').update(content).digest('hex').slice(0, 10);
const write = (file, content) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
};

// Conservative CSS minification: comments and insignificant whitespace only.
function minifyCss(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\s+/g, ' ')
    .replace(/\s*([{};])\s*/g, '$1')
    .replace(/;}/g, '}')
    .trim();
}

// Conservative JS minification: whole-line comments and indentation only.
// Line breaks are kept, so automatic semicolon insertion behaves exactly as in source.
function minifyJs(js) {
  return js
    .replace(/^\s*\/\*[\s\S]*?\*\/\s*$/gm, '')
    .replace(/^\s*\/\/.*$/gm, '')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join('\n');
}

// Copies an asset to dist/ under a content-hashed name and records the mapping.
function fingerprint(assetMap, publicPath, content) {
  const ext = path.extname(publicPath);
  const hashedPath = `${publicPath.slice(0, -ext.length)}.${hash(content)}${ext}`;
  write(path.join(DIST, hashedPath), content);
  assetMap.set(publicPath, hashedPath);
}

function rewriteAssetPaths(text, assetMap) {
  let output = text;
  for (const [original, hashed] of assetMap) output = output.split(original).join(hashed);
  return output;
}

function structuredData(config) {
  const organization = {
    '@type': 'Organization',
    '@id': `${config.url}/#organization`,
    name: config.name,
    url: `${config.url}/`,
    logo: `${config.url}/brand/inskavex-mark.png`,
    description: config.description,
    slogan: config.tagline,
  };
  if (config.legal.entityName) organization.legalName = config.legal.entityName;
  if (config.contact.emailEnabled) organization.email = config.contact.email;

  const data = {
    '@context': 'https://schema.org',
    '@graph': [
      organization,
      {
        '@type': 'WebSite',
        '@id': `${config.url}/#website`,
        name: config.name,
        url: `${config.url}/`,
        publisher: { '@id': `${config.url}/#organization` },
        inLanguage: 'en',
      },
    ],
  };
  // Escape "<" so the JSON can never close the surrounding <script> element.
  return JSON.stringify(data).replace(/</g, '\\u003c');
}

function inlineScriptHashes(html) {
  const hashes = new Set();
  for (const [, attrs, body] of html.matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/g)) {
    if (/\bsrc=/.test(attrs) || /application\/ld\+json/.test(attrs)) continue;
    hashes.add(`'sha256-${crypto.createHash('sha256').update(body).digest('base64')}'`);
  }
  return hashes;
}

function headersFile(config, scriptHashes) {
  const form = config.contact.formOrigin ? ` ${config.contact.formOrigin}` : '';
  const csp = [
    "default-src 'none'",
    `script-src 'self' ${[...scriptHashes].join(' ')}`.trim(),
    "style-src 'self'",
    "img-src 'self' data:",
    "font-src 'self'",
    `connect-src 'self'${form}`,
    `form-action 'self'${form}`,
    "manifest-src 'self'",
    "base-uri 'none'",
    "object-src 'none'",
    "frame-ancestors 'none'",
  ].join('; ');

  const lines = [
    '# Generated by scripts/build.mjs — edit the build script, not this file.',
    '/*',
    `  Content-Security-Policy: ${csp}`,
    '  X-Content-Type-Options: nosniff',
    '  X-Frame-Options: DENY',
    '  Referrer-Policy: strict-origin-when-cross-origin',
    '  Permissions-Policy: accelerometer=(), browsing-topics=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()',
    '  Cross-Origin-Opener-Policy: same-origin',
    '  Strict-Transport-Security: max-age=31536000',
  ];
  if (!config.allowIndexing) lines.push('  X-Robots-Tag: noindex, nofollow');
  lines.push('', '/assets/*', '  Cache-Control: public, max-age=31536000, immutable', '');
  return lines.join('\n');
}

function sitemapXml(config, pages) {
  const urls = pages
    .filter((page) => page.sitemap)
    .map(
      (page) =>
        `  <url>\n    <loc>${escapeHtml(config.url + page.path)}</loc>\n    <lastmod>${config.buildDate}</lastmod>\n  </url>`,
    )
    .join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
}

function robotsTxt(config) {
  return config.allowIndexing
    ? `User-agent: *\nAllow: /\n\nSitemap: ${config.url}/sitemap.xml\n`
    : 'User-agent: *\nDisallow: /\n';
}

export function build({ quiet = false } = {}) {
  const started = Date.now();
  const config = loadConfig();

  fs.rmSync(DIST, { recursive: true, force: true });
  fs.cpSync(path.join(SRC, 'public'), DIST, { recursive: true });

  // Fingerprinted assets: fonts first, since the stylesheet references them.
  const assetMap = new Map();
  const fontsDir = path.join(SRC, 'assets/fonts');
  for (const file of fs.readdirSync(fontsDir)) {
    const content = fs.readFileSync(path.join(fontsDir, file));
    if (file.endsWith('.woff2')) fingerprint(assetMap, `/assets/fonts/${file}`, content);
    else write(path.join(DIST, 'assets/fonts', file), content); // licences
  }
  const css = fs.readFileSync(path.join(SRC, 'assets/css/styles.css'), 'utf8');
  fingerprint(assetMap, '/assets/css/styles.css', minifyCss(rewriteAssetPaths(css, assetMap)));
  fingerprint(assetMap, '/assets/js/main.js', minifyJs(fs.readFileSync(path.join(SRC, 'assets/js/main.js'), 'utf8')));

  // Pages.
  const pages = [];
  const scriptHashes = new Set();
  const context = { site: config, jsonLd: structuredData(config) };
  const pagesDir = path.join(SRC, 'pages');
  for (const file of fs.readdirSync(pagesDir).filter((name) => name.endsWith('.html'))) {
    const source = `src/pages/${file}`;
    const parsed = readFrontMatter(fs.readFileSync(path.join(pagesDir, file), 'utf8'), source);
    const page = { index: true, sitemap: true, ...parsed.page };
    page.canonical = config.url + page.path;
    page.robots = config.allowIndexing && page.index ? 'index, follow' : 'noindex, follow';
    const html = rewriteAssetPaths(
      render(parsed.body, { ...context, page }, { partialsDir: path.join(SRC, 'partials'), source }),
      assetMap,
    )
      .replace(/[ \t]+$/gm, '') // whitespace left behind by template conditionals
      .replace(/\n{3,}/g, '\n\n');
    for (const value of inlineScriptHashes(html)) scriptHashes.add(value);
    write(path.join(DIST, file), html);
    pages.push(page);
  }

  write(path.join(DIST, 'sitemap.xml'), sitemapXml(config, pages));
  write(path.join(DIST, 'robots.txt'), robotsTxt(config));
  write(path.join(DIST, '_headers'), headersFile(config, scriptHashes));

  if (!quiet) {
    console.log(`Built ${pages.length} pages into ${path.relative(ROOT, DIST)}/ in ${Date.now() - started} ms (site URL: ${config.url}).`);
    const issues = launchIssues(config);
    if (issues.length) {
      console.log('\nNot yet configured for public launch (see README → Configuration):');
      for (const issue of issues) console.log(`  • ${issue}`);
    }
  }
  return { config, pages };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    build();
  } catch (error) {
    console.error(`Build failed: ${error.message}`);
    process.exit(1);
  }
}
