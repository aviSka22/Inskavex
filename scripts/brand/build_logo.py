"""Generate the Texponex logo assets from the brand font.

The wordmark is converted to outlined SVG paths so the logo never depends on a
font loading. Run from the repository root (requires `pip install fonttools brotli`):

    python3 scripts/brand/build_logo.py

Outputs:
    src/public/brand/texponex-mark.svg        symbol only (ink + ember)
    src/public/brand/texponex-logo.svg        lockup for light backgrounds
    src/public/brand/texponex-logo-light.svg  lockup for dark backgrounds
    src/public/favicon.svg                    adaptive favicon (light/dark tabs)
    src/partials/logo.html                    inline lockup using currentColor
"""

from pathlib import Path

import math

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "src/assets/fonts/archivo-var.woff2"

WORD = "Texponex"
WIDTH_AXIS = 112   # semi-expanded, matches display type on the site
WEIGHT_AXIS = 640
TRACKING = -0.012  # em, slight tightening for a compact wordmark

INK = "#0E0F0D"
BONE = "#F3F1EC"
EMBER = "#F0532D"

# Mark geometry on a 32-unit square: a block with its top-right quadrant lifted
# out and offset up and to the right — "the next piece".
MARK_INK = "M0 6H13V19H26V32H0Z"
MARK_NEXT = "M19 0H32V13H19Z"
MARK_SIZE = 32

CAP_HEIGHT = 20   # wordmark cap height in mark units
GAP = 10          # space between mark and wordmark


def wordmark_paths():
    font = TTFont(FONT)
    font = instantiateVariableFont(font, {"wdth": WIDTH_AXIS, "wght": WEIGHT_AXIS})
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    cap = font["OS/2"].sCapHeight
    scale = CAP_HEIGHT / cap
    upm = font["head"].unitsPerEm

    x = 0.0
    parts = []
    lowest = 0  # deepest descender below the baseline, in font units
    for char in WORD:
        name = cmap[ord(char)]
        pen = SVGPathPen(glyph_set, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
        # Flip the y axis and place the baseline at the bottom of the mark.
        glyph_set[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, MARK_SIZE)))
        parts.append(pen.getCommands())
        bounds = BoundsPen(glyph_set)
        glyph_set[name].draw(bounds)
        if bounds.bounds:
            lowest = min(lowest, bounds.bounds[1])
        x += (glyph_set[name].width + TRACKING * upm) * scale
    # Descenders (e.g. "p") hang below the mark; the artwork is extended to fit them.
    descent = math.ceil(-lowest * scale * 2) / 2
    return " ".join(parts), x - TRACKING * upm * scale, descent


def lockup_svg(text_fill, mark_fill, title=True, extra=""):
    path, width, descent = wordmark_paths()
    total = MARK_SIZE + GAP + width
    height = MARK_SIZE + descent
    offset = MARK_SIZE + GAP
    head = f'<title>Texponex</title>' if title else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {total:.2f} {height:g}" '
        f'width="{total:.0f}" height="{height:g}"{extra}>{head}'
        f'<path fill="{mark_fill}" d="{MARK_INK}"/>'
        f'<path fill="{EMBER}" d="{MARK_NEXT}"/>'
        f'<path fill="{text_fill}" transform="translate({offset} 0)" d="{path}"/>'
        f"</svg>\n"
    ), total


def main():
    brand = ROOT / "src/public/brand"
    brand.mkdir(parents=True, exist_ok=True)

    svg, _ = lockup_svg(INK, INK, extra=' role="img" aria-label="Texponex"')
    (brand / "texponex-logo.svg").write_text(svg)
    svg, _ = lockup_svg(BONE, BONE, extra=' role="img" aria-label="Texponex"')
    (brand / "texponex-logo-light.svg").write_text(svg)

    (brand / "texponex-mark.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="32" height="32" '
        f'role="img" aria-label="Texponex"><title>Texponex</title>'
        f'<path fill="{INK}" d="{MARK_INK}"/><path fill="{EMBER}" d="{MARK_NEXT}"/></svg>\n'
    )

    (ROOT / "src/public/favicon.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">'
        f"<style>.i{{fill:{INK}}}@media (prefers-color-scheme:dark){{.i{{fill:{BONE}}}}}</style>"
        f'<path class="i" d="{MARK_INK}"/><path fill="{EMBER}" d="{MARK_NEXT}"/></svg>\n'
    )

    path, width, descent = wordmark_paths()
    total = MARK_SIZE + GAP + width
    height = MARK_SIZE + descent
    (ROOT / "src/partials/logo.html").write_text(
        "<!-- Generated by scripts/brand/build_logo.py — do not edit by hand. -->\n"
        f'<svg class="logo" viewBox="0 0 {total:.2f} {height:g}" width="{total:.0f}" '
        f'height="{height:g}" aria-hidden="true" focusable="false">'
        f'<path fill="currentColor" d="{MARK_INK}"/>'
        f'<path class="logo__next" d="{MARK_NEXT}"/>'
        f'<path fill="currentColor" transform="translate({MARK_SIZE + GAP} 0)" d="{path}"/>'
        "</svg>\n"
    )
    print(f"Logo assets written (lockup {total:.1f} × {height:g}; descender {descent:g} below the mark).")


if __name__ == "__main__":
    main()
